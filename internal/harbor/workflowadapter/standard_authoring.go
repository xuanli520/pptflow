type standardAuthoringRepairFeedback struct {
	input    workflowkit.ArtifactSpec
	resource workflowkit.ResourceKey
}

func standardAuthoringRepairFeedbackForStage(key workflowkit.StageKey) []standardAuthoringRepairFeedback {
	feedback := make([]standardAuthoringRepairFeedback, 0, 3)
	if key == workflowkit.StageKey(RepoAnalyze) || key == workflowkit.StageKey(TaskDesign) {
		feedback = append(feedback, standardAuthoringRepairFeedback{
			input:    optionalReviewDecisionInput("task_review_decision").spec,
			resource: resourceReviewTaskDirection,
		})
	}
	if key == workflowkit.StageKey(InstructionGen) || key == workflowkit.StageKey(TaskTOMLGen) || key == workflowkit.StageKey(DockerfileGen) || key == workflowkit.StageKey(DockerfileBuildValidate) {
		feedback = append(feedback, standardAuthoringRepairFeedback{
			input:    optionalReviewDecisionInput("content_review_decision").spec,
			resource: resourceReviewContent,
		})
	}
	if standardAuthoringStageRepairsPackageContent(key) {
		feedback = append(feedback,
			standardAuthoringRepairFeedback{
				input:    optionalReviewDecisionInput("solution_review_decision").spec,
				resource: resourceReviewSolutionVerifier,
			},
			standardAuthoringRepairFeedback{
				input:    optionalArtifactInputWithSchema("codeedge_package_admission_report", "harbor.standard-authoring-task-package-admission.v1").spec,
				resource: resourceAuthoringTaskAdmission,
			},
		)
	}
	return feedback
}

func standardAuthoringStageRepairsPackageContent(key workflowkit.StageKey) bool {
	switch key {
	case workflowkit.StageKey(InstructionGen), workflowkit.StageKey(TaskTOMLGen), workflowkit.StageKey(DockerfileGen),
		workflowkit.StageKey(DockerfileBuildValidate), workflowkit.StageKey(SolveGen), workflowkit.StageKey(TestGen),
		workflowkit.StageKey(AuthoringHarness), workflowkit.StageKey(TestsAnalysis):
		return true
	default:
		return false
	}
}
