const (
	// StandardAuthoringWorkflowTemplateID and Version identify the closed
	// pre-materialization workflow. Its subject is an immutable
	// AuthoringSession/source snapshot, not an empty TaskRevision. The final
	// materialize_task stage atomically creates the first task revision and
	// emits an explicit handoff for a separate task-bound CodeEdge Phase-1 Run.
	StandardAuthoringWorkflowTemplateID      = "harbor.standard-authoring"
	StandardAuthoringWorkflowTemplateVersion = "1.2.0"

	// StandardAuthoringTaskAdmissionTemplateVersion is reserved for the
	// additive Authoring contract release. Keeping it distinct from 1.2.0
	// prevents a new production binary from reinterpreting a frozen legacy Run.
	StandardAuthoringTaskAdmissionTemplateVersion = "1.3.0"

	// StandardAuthoringBriefTemplateVersion adds the immutable authoring_brief
	// input while preserving the exact 1.2.0 and 1.3.0 templates for historical
	// parsing and recovery.
	StandardAuthoringBriefTemplateVersion = "1.4.0"

	// StandardAuthoringRepairFeedbackTemplateVersion adds optional, durable and
	// immutable downstream review and admission artifacts to the stages that may be
	// regenerated by a repair continuation. The 1.4.0 brief template remains
	// registered unchanged for historical Run parsing and recovery.
	StandardAuthoringRepairFeedbackTemplateVersion = "1.5.0"

	// StandardAuthoringTestsAnalysisInputTemplateVersion binds generators to the
	// current reviewed Dockerfile and orders tests_analysis after test_generate so
	// repair feedback can be evaluated against the regenerated test script. The
	// 1.5.0 repair-feedback template remains registered unchanged for historical
	// Run parsing.
	StandardAuthoringTestsAnalysisInputTemplateVersion = "1.6.0"

	// StandardAuthoringHarnessTemplateVersion adds two bounded ReAct validation
	// stages. dockerfile_build_validate produces the exact Dockerfile reviewed by
	// content_review, while authoring_harness repairs and proves the final solve
	// and test scripts with initial-fail plus oracle-pass execution. The 1.6.0
	// template remains registered unchanged for historical Run parsing.
	StandardAuthoringHarnessTemplateVersion = "1.7.0"

	// StandardAuthoringFixedFileTemplateVersion preserves the 1.7.0 DAG and
	// Docker ReAct evidence contract, while changing only solve_generate and
	// test_generate's artifact handoff: each script is host-read from an
	// attempt-scoped fixed workspace file after a pass-only receipt. Keeping it
	// separate prevents a new executor from reinterpreting frozen 1.7.0 base64
	// turn programs.
	StandardAuthoringFixedFileTemplateVersion = "1.8.0"

	standardAuthoringCatalogID      = "harbor.standard-authoring-stage-catalog"
	standardAuthoringCatalogVersion = "1.2.0"

	// StandardAuthoringTaskDesignMaxTurns bounds the task-design Codex
	// conversation in this source-session template. It intentionally does not
	// alter the task-bound Standard catalog, whose task_design stage remains a
	// separate workflow contract.
	StandardAuthoringTaskDesignMaxTurns = 30

	// StandardAuthoringTaskHandoffArtifact is emitted only by materialize_task.
	// It is a receipt for a newly sealed task revision, not a mutable workspace
	// path and not an authorization to continue task-bound work in the source
	// AuthoringSession Run.
	StandardAuthoringTaskHandoffArtifact               = "authoring_task_handoff"
	StandardAuthoringTaskHandoffSchemaVersion          = "harbor.authoring-task-handoff.v1"
	StandardAuthoringTaskAdmissionHandoffSchemaVersion = "harbor.authoring-task-handoff.v2"

	StandardAuthoringValidatedDockerfileArtifact        = "validated_dockerfile"
	StandardAuthoringDockerfileBuildReportArtifact      = "dockerfile_build_report"
	StandardAuthoringDockerfileBuildReportSchemaVersion = "harbor.standard-authoring-dockerfile-build-report.v1"
	StandardAuthoringValidatedSolveScriptArtifact       = "validated_solve_script"
	StandardAuthoringValidatedTestScriptArtifact        = "validated_test_script"
	StandardAuthoringHarnessReportArtifact              = "authoring_harness_report"
	StandardAuthoringHarnessReportSchemaVersion         = "harbor.standard-authoring-harness-report.v1"
)

